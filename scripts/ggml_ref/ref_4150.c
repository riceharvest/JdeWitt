int main(int argc, char ** argv) {
    if (argc < 2) { fprintf(stderr, "usage: ref_4150 MODE [dequant|quantize]\n"); return 2; }
    const char * m = argv[1];
    size_t bs = 0;
    if (!strcmp(m, "q4_1")) bs = 20;
    else if (!strcmp(m, "q5_0")) bs = 22;
    else if (!strcmp(m, "q5_1")) bs = 24;
    else { fprintf(stderr, "bad mode\n"); return 2; }
    int quantize = (argc > 2 && !strcmp(argv[2], "quantize"));
    size_t cap = 1 << 20;
    float * fbuf = malloc(cap * sizeof(float));
    uint8_t * bbuf = malloc(cap * bs);
    size_t n;
    if (quantize) {
        while ((n = fread(fbuf, sizeof(float), cap, stdin)) > 0) {
            if (n % QK4N) { fprintf(stderr, "not multiple of 32\n"); return 2; }
            if (!strcmp(m, "q4_1")) quantize_row_q4_1_ref(fbuf, (block_q4_1 *) bbuf, (int64_t)n);
            else if (!strcmp(m, "q5_0")) quantize_row_q5_0_ref(fbuf, (block_q5_0 *) bbuf, (int64_t)n);
            else quantize_row_q5_1_ref(fbuf, (block_q5_1 *) bbuf, (int64_t)n);
            size_t want = n / QK4N * bs;
            if (fwrite(bbuf, 1, want, stdout) != want) return 2;
        }
    } else {
        while ((n = fread(bbuf, bs, cap, stdin)) > 0) {
            int64_t k = (int64_t)n * QK4N;
            if (!strcmp(m, "q4_1")) dequantize_row_q4_1((const block_q4_1 *) bbuf, fbuf, k);
            else if (!strcmp(m, "q5_0")) dequantize_row_q5_0((const block_q5_0 *) bbuf, fbuf, k);
            else dequantize_row_q5_1((const block_q5_1 *) bbuf, fbuf, k);
            if (fwrite(fbuf, sizeof(float), n * QK4N, stdout) != n * QK4N) return 2;
        }
    }
    return 0;
}
