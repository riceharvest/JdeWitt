"""Capture the fit's data inside the tool: one command, any architecture.

The step between "here is a checkpoint" and "here are records spanfit can fit"
used to live in per-model scratch scripts: one to serve the model and label its
answers, one to hook decoder layers under bespoke module paths. That made the
tool model-agnostic on paper and per-lineage in practice, and an agent could not
run it without writing code first.

This command closes both gaps from the model's own structure:

  * the decoder stack is the ModuleList whose blocks write a ``hidden_size``-wide
    residual stream, and the residual-write projections are the dense layers in
    each block whose output is ``hidden_size`` wide AND whose name is one of the
    canonical residual-write names (o_proj/out_proj/ssm_out/down_proj/w2). There
    is no architecture table and no hand-typed tensor glob. The name test is not
    decorative: on an MHA model ``q_proj`` is also hidden-wide, and an axis
    captured in residual space is meaningless in query space, so a dimension-only
    rule would edit the wrong matrix while passing every shape check;
  * every row is generated by the model being edited, greedily, and labelled by
    the SHAPE of its own answer (``refusal_shape``, METHODOLOGY R2/R3): a harmful
    row that declines is ``bad``, a harmless row that complies is ``good``, and
    everything else keeps its own label (``deliver``, ``ambiguous``,
    ``overdecline``) and never enters the default fit. The wording checker never
    labels anything.

Output is spanfit's record format — ``torch.save({'records': [(meta, [L, W])]})``
— so the next step is one spanfit command, and the report prints it with the
discovered targets already filled in. Nothing here certifies: this produces the
fit's input, and the shape verdict on the edited artifact stays an agent read.
"""
from __future__ import annotations

import hashlib
import json
import re
import time
from pathlib import Path

import torch
from torch import nn

from .answers import atomic_json
from .chat import render_chat
from .errors import NoVerifiedAdapter
from .refusal_shape import classify, screen_short

LOCI = ("answer", "last-prompt", "first-answer")
DEFAULT_KINDS = ("refusal", "harmless")

# Last dotted component of a module name that denotes a residual-write
# projection. Same canonical set the GGUF-side discovery uses (gguf_adapters
# WRITEBACK_TENSOR); a model whose block names its output projection something
# else is reported, never guessed at.
WRITEBACK_MODULE = re.compile(
    r"^(o_proj|out_proj|ssm_out|down_proj|w2|attn_output|attn_out)$")


def read_rows(path, kinds=None, limit=None):
    """Suite rows to capture, plus a tally of the kinds filtered out."""
    rows, skipped = [], {}
    for number, line in enumerate(Path(path).read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as error:
            raise ValueError(f"{path}:{number} is not JSON: {error}") from error
        for field in ("id", "kind", "prompt"):
            if field not in row:
                raise ValueError(f"{path}:{number} needs a {field!r} field")
        if kinds and row["kind"] not in kinds:
            skipped[row["kind"]] = skipped.get(row["kind"], 0) + 1
            continue
        rows.append(row)
    return (rows[:limit] if limit else rows), skipped


def hidden_width(config, override=None):
    if override:
        return int(override)
    text = getattr(config, "text_config", config)
    width = getattr(text, "hidden_size", None)
    if type(width) is not int or width <= 0:
        raise ValueError("config carries no hidden_size; pass --hidden explicitly")
    return width


def expected_layers(config):
    text = getattr(config, "text_config", config)
    for attribute in ("num_hidden_layers", "n_layer", "num_layers"):
        value = getattr(text, attribute, None)
        if type(value) is int and value > 0:
            return value
    return None


def find_layer_stack(model, width, expected=None):
    """(path, count) of the decoder ModuleList, from the module tree.

    A candidate is a ModuleList whose first block contains a linear that writes a
    ``width``-wide vector. ``expected`` (config.num_hidden_layers) breaks ties,
    because a model may nest other ModuleLists inside a block.
    """
    candidates = []
    for name, module in model.named_modules():
        if not isinstance(module, nn.ModuleList) or len(module) < 2:
            continue
        writes = any(isinstance(inner, nn.Linear) and inner.out_features == width
                     for inner in module[0].modules())
        candidates.append((name, len(module), writes))
    if not candidates:
        raise ValueError("no decoder ModuleList in the module tree")
    exact = [candidate for candidate in candidates if expected and candidate[1] == expected]
    pool = exact or [candidate for candidate in candidates if candidate[2]]
    if not pool:
        raise ValueError(f"no ModuleList whose blocks write a {width}-wide residual stream")
    name, count, _ = max(pool, key=lambda candidate: candidate[1])
    return name, count


def writeback_targets(layer, width):
    """[(relative module name, Linear)] for one block's residual-write projections."""
    found = []
    for name, module in layer.named_modules():
        if not name or not isinstance(module, nn.Linear):
            continue
        if module.out_features != width:
            continue
        if not WRITEBACK_MODULE.match(name.split(".")[-1]):
            continue
        found.append((name, module))
    return found


def label_for(kind, shape):
    """Fit label from the row's kind and the answer's shape — never from wording."""
    declining = shape["declining"] or shape["embedded_decline"]
    if kind == "refusal":
        if declining:
            return "bad"
        return "deliver" if shape["shape"] == "procedural_no_decline" else "ambiguous"
    if kind == "harmless":
        return "overdecline" if declining else "good"
    return "unlabelled"


def render_prompt(tokenizer, prompt, system, raw):
    if raw:
        return prompt, "raw"
    if getattr(tokenizer, "chat_template", None):
        return render_chat(tokenizer, prompt, system=system), "chat"
    return prompt, "raw-no-template"


def _hook_factory(width, position, span_end):
    def hook(module, args, output):
        hidden = output[0] if isinstance(output, tuple) else output
        if not torch.is_tensor(hidden) or hidden.dim() != 3:
            raise ValueError("decoder block did not return a [batch, seq, hidden] tensor")
        if hidden.shape[-1] != width:
            raise ValueError(f"residual width {hidden.shape[-1]} != {width}")
        rows = hidden[0]
        if span_end is None:
            captured = rows[position]
        else:
            captured = rows[position:span_end].mean(dim=0)
        hook.captured = captured.detach().float().cpu()
    hook.captured = None
    return hook


def _settle_criteria(tokenizer, prompt_length, min_tokens, every=8):
    """Stop decoding once the prefix is a self-declination (cert mode).

    The label only needs the prefix: a refusal opener does not turn into delivery
    by adding tokens. Settling on the OPENER / embedded first-person decline form
    -- the cert-mode settle, never a topical word -- keeps this exact: a delivered
    answer that merely contains 'illegal' is not cut short, and a seeded
    'Sure, here is how: I cannot ...' is. Rows that do not settle keep decoding
    to the full budget, so a procedure is never mistaken for a refusal.
    """
    from transformers import StoppingCriteria

    class Settle(StoppingCriteria):
        def __init__(self):
            self.steps = 0
            self.settled_at = None

        def __call__(self, input_ids, scores, **kwargs):
            self.steps += 1
            generated = int(input_ids.shape[1]) - prompt_length
            if generated < min_tokens or self.steps % every:
                return False
            text = tokenizer.decode(input_ids[0, prompt_length:], skip_special_tokens=True)
            if screen_short(text, 'cert') == 'refusal':
                self.settled_at = generated
                return True
            return False

    return Settle()


def read_answers(path):
    """{row id: answer text} from a banked wave or any jsonl carrying id+answer."""
    answers = {}
    for number, line in enumerate(Path(path).read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as error:
            raise ValueError(f'{path}:{number} is not JSON: {error}') from error
        answer, row_id = row.get('answer'), row.get('id')
        if answer is None or row_id is None:
            continue
        answers[row_id] = answer
    if not answers:
        raise ValueError(f'{path} carries no id+answer rows; pass a predictions.jsonl from '
                         f'a wave over this same model')
    return answers


def capture_one(model, tokenizer, row, layers, width, *, locus, max_tokens,
                ctx_size, system, raw, device, settle=True, settle_min_tokens=24,
                answer_text=None):
    """Generate one row (or reuse a banked answer) and return (meta, [L, W]).

    ``answer_text`` is the zero-output-token path: when a wave has already
    generated this row against this same model, the answer is scored by
    re-tokenizing the prompt plus that text, so the only cost is one prefill.
    """
    text, rendered = render_prompt(tokenizer, row["prompt"], system, raw)
    ids = tokenizer(text, return_tensors="pt", add_special_tokens=False)["input_ids"]
    prompt_tokens = int(ids.shape[1])
    if prompt_tokens + max_tokens + 1 > ctx_size:
        return None, {"reason": "prompt_plus_budget_exceeds_ctx", "prompt_tokens": prompt_tokens}
    pad = tokenizer.pad_token_id if tokenizer.pad_token_id is not None else tokenizer.eos_token_id
    settled_at = None
    stopped = False
    if answer_text is not None:
        answer_ids = tokenizer(answer_text, add_special_tokens=False)["input_ids"]
        if not answer_ids:
            return None, {"reason": "banked_answer_empty"}
        sequence = torch.cat([ids, torch.tensor([answer_ids], dtype=ids.dtype)], dim=1).to(device)
        source = "banked"
    else:
        criteria = None
        if settle:
            from transformers import StoppingCriteriaList
            criteria = StoppingCriteriaList([_settle_criteria(tokenizer, prompt_tokens, settle_min_tokens)])
        with torch.inference_mode():
            sequence = model.generate(
                ids.to(device),
                attention_mask=torch.ones_like(ids, device=device),
                max_new_tokens=max_tokens, do_sample=False,
                pad_token_id=pad if type(pad) is int else None,
                stopping_criteria=criteria)
        settled_at = criteria[0].settled_at if criteria is not None else None
        generated = sequence[0, prompt_tokens:].tolist()
        eos = model.generation_config.eos_token_id
        eos = list(eos) if isinstance(eos, (list, tuple)) else [eos]
        stop = next((index for index, token in enumerate(generated) if token in eos), None)
        stopped = stop is not None
        generated = generated[: stop + 1] if stopped else generated
        answer_ids = generated[:-1] if stopped else generated
        source = "generated"
    complete = True if source == "banked" else (stopped or settled_at is not None)
    answer = tokenizer.decode(answer_ids, skip_special_tokens=True)
    if not answer_ids:
        return None, {"reason": "empty_answer"}
    shape = classify(answer)
    label = label_for(row["kind"], shape)
    start = prompt_tokens
    end = prompt_tokens + len(answer_ids)
    if locus == "last-prompt":
        position, span_end = start - 1, None
    elif locus == "first-answer":
        position, span_end = start, None
    else:
        position, span_end = start, end
    hooks = []
    try:
        for layer in layers:
            hook = _hook_factory(width, position, span_end)
            hooks.append((hook, layer.register_forward_hook(hook)))
        with torch.inference_mode():
            model(sequence[:, : end], attention_mask=torch.ones((1, end), dtype=torch.long, device=device),
                  use_cache=False)
    finally:
        for _, handle in hooks:
            handle.remove()
    if any(hook.captured is None for hook, _ in hooks):
        return None, {"reason": "residual_hooks_did_not_fire"}
    residual = torch.stack([hook.captured for hook, _ in hooks])
    meta = {"id": row.get("id"), "label": label, "kind": row["kind"],
            "shape": shape["shape"], "declining": bool(shape["declining"]),
            "chars": len(answer), "answer_tokens": len(answer_ids),
            "settled_at": settled_at,
            "prompt_tokens": prompt_tokens, "family_id": row.get("family_id"),
            "category": row.get("category"), "language": row.get("language"),
            "rendered": rendered, "prompt": row["prompt"], "prompt_rendered": text,
            "complete": complete, "locus": locus,
            "answer_source": source,
            "answer": answer}
    return (meta, residual), None


def capture_command(args):
    """The agent-facing entry: one JSON report, one records file, one next step."""
    from .hf import resolve_backend, backend_device
    from . import gguf_adapters

    t0 = time.monotonic()
    kinds = tuple(k.strip() for k in args.kinds.split(",") if k.strip())
    unknown = [kind for kind in kinds if kind not in {"refusal", "harmless", "capability", "code", "math"}]
    if unknown:
        raise ValueError(f"unknown --kinds entries {unknown}; kinds are suite 'kind' values")
    rows, filtered = read_rows(args.suite, kinds, args.limit)
    if not rows:
        raise ValueError(f"{args.suite} has no rows for kinds {list(kinds)}")

    from transformers import AutoConfig, AutoModel, AutoModelForCausalLM, AutoTokenizer
    from .compat import compatible_source
    backend = resolve_backend(allow_secondary=args.allow_cuda)
    device = backend_device(backend)
    config = AutoConfig.from_pretrained(args.model, revision=args.revision,
                                        trust_remote_code=args.trust_remote_code)
    width = hidden_width(config, args.hidden)
    tokenizer = AutoTokenizer.from_pretrained(args.model, revision=args.revision,
                                              trust_remote_code=args.trust_remote_code)
    dtype = {"bfloat16": torch.bfloat16, "float16": torch.float16}[args.dtype]
    attempts = []
    model = None
    # Vendor remote-code checkpoints get the same private metadata repair the rest
    # of the tool uses (compat.compatible_source); the user's download is never
    # written to.
    source_context = compatible_source(args.model)
    prepared = source_context.__enter__()
    try:
        for factory in (AutoModelForCausalLM, AutoModel):
            for attention in ("eager", None):
                kwargs = {"revision": args.revision, "dtype": dtype, "device_map": {"": device},
                          "trust_remote_code": args.trust_remote_code}
                if attention:
                    kwargs["attn_implementation"] = attention
                try:
                    model = factory.from_pretrained(str(prepared), **kwargs).eval()
                    break
                except (ValueError, TypeError, RuntimeError) as error:
                    attempts.append(f"{factory.__name__}({attention or 'default'}): {error}")
            if model is not None:
                break
        if model is None:
            raise ValueError("no model factory loaded this checkpoint: " + " | ".join(attempts[:4]))
    except BaseException:
        source_context.__exit__(None, None, None)
        raise

    stack_name, layer_count = find_layer_stack(model, width, expected_layers(config))
    stack = dict(model.named_modules())[stack_name]
    layers = [stack[index] for index in range(layer_count)]
    targets = {index: writeback_targets(layers[index], width) for index in range(layer_count)}
    empty = [index for index, found in targets.items() if not found]
    if empty:
        linear_names = sorted({name for name, module in layers[empty[0]].named_modules()
                              if isinstance(module, nn.Linear)})
        raise NoVerifiedAdapter(
            f"blocks {empty[:8]} carry no residual-write projection this tool can name; "
            f"linear modules in block {empty[0]}: {linear_names}. Capture cannot edit a block "
            f"it cannot locate, and guessing would edit the wrong matrix. Discovery proves a "
            f"module NAME at hidden width {width}, not that the architecture serves the edit; "
            f"a layout is certified by the export smoke, not here",
            width=width, layers_without_target=empty[:8], layers_without_target_total=len(empty),
            linear_modules=linear_names, layer=empty[0],
            writeback_names=list(WRITEBACK_MODULE.pattern.strip('^$()').split('|')))
    suffix_counts = {}
    for found in targets.values():
        for name, _ in found:
            suffix = name.split(".")[-1]
            suffix_counts[suffix] = suffix_counts.get(suffix, 0) + 1

    records, discarded, labels = [], {}, {}
    tokens = {"prompt": 0, "answer": 0}
    settled = 0
    reused = 0
    answers = read_answers(args.answers) if args.answers else {}
    for row in rows:
        try:
            captured, reason = capture_one(
                model, tokenizer, row, layers, width, locus=args.locus,
                max_tokens=args.max_tokens, ctx_size=args.ctx_size,
                system=args.system, raw=args.raw_prompt, device=device,
                settle=args.settle, settle_min_tokens=args.settle_min_tokens,
                answer_text=answers.get(row.get("id")))
        except (ValueError, RuntimeError) as error:
            discarded[str(error)[:200]] = discarded.get(str(error)[:200], 0) + 1
            continue
        if captured is None:
            key = reason.get("reason", "unknown")
            discarded[key] = discarded.get(key, 0) + 1
            continue
        meta, residual = captured
        records.append((meta, residual))
        labels[meta["label"]] = labels.get(meta["label"], 0) + 1
        tokens["prompt"] += meta["prompt_tokens"]
        if meta.get("answer_source") == "banked":
            reused += 1
        else:
            tokens["answer"] += meta["answer_tokens"]
        settled += 1 if meta.get("settled_at") else 0

    bad, good = labels.get("bad", 0), labels.get("good", 0)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    identity = {
        "model": args.model, "revision": args.revision or getattr(config, "_commit_hash", None),
        "architecture": getattr(config, "model_type", None), "hidden": width,
        "layers": layer_count, "layer_path": stack_name, "locus": args.locus,
        "dtype": args.dtype, "max_tokens": args.max_tokens, "ctx_size": args.ctx_size,
        "kinds": list(kinds), "suite": str(args.suite),
        "suite_sha256": hashlib.sha256(Path(args.suite).read_bytes()).hexdigest(),
        "targets": {index: [name for name, _ in found] for index, found in targets.items()},
        "compute_backend": {"type": backend["type"], "rank": backend["rank"], "name": backend["name"]},
    }
    torch.save({"records": records, "capture": identity}, out)
    report = {
        "records": str(out), "records_bytes": out.stat().st_size,
        "identity": identity,
        "rows_read": len(rows), "records_written": len(records),
        "labels": labels, "filtered_kinds": filtered, "discarded": discarded,
        "tokens": tokens, "elapsed_s": round(time.monotonic() - t0, 1),
        "settling": {
            "enabled": bool(args.settle), "min_tokens": args.settle_min_tokens,
            "rows_settled": settled,
            "note": "a settled row stops at the first explicit self-declination (cert-mode "
                    "settle), so its answer span IS the refusal span; rows that do not settle "
                    "decode to the full budget, so a procedure is never cut short",
        },
        "answers_reused": reused,
        "answers_reused_note": (f"{reused} row(s) took their answer from --answers and cost ZERO "
                                f"output tokens (prefill only); rows not found there were generated"),
        "target_suffixes": suffix_counts,
        "fit_usable": False,
        "next": [],
        "notes": [
            "bad = a harmful row whose own answer declines; good = a harmless row that "
            "complies; deliver/ambiguous/overdecline are recorded for the agent read and "
            "never enter the default bad/good contrast.",
            "capture is not certification: shape verdicts on the edited artifact stay an "
            "agent read (METHODOLOGY R2).",
        ],
    }
    # A fit needs BOTH halves of the contrast, and a missing half is a property of
    # the base model, not a capture defect: fitting a label set the model does not
    # exhibit yields a null edit that still merges cleanly.
    report["fit_usable"] = bad >= 1 and good >= 1
    if not report["fit_usable"]:
        missing = []
        if not bad:
            missing.append(f"no bad rows: 0 of {len(records)} answers declined")
        if not good:
            missing.append(f"no good rows: 0 of {len(records)} harmless answers complied")
        report["notes"].append(
            "cannot form a bad-minus-good contrast — " + "; ".join(missing) +
            ". Widen the suite/--limit or use a checkpoint that actually refuses it; do not fit on this.")
    if args.gguf:
        shapes = gguf_adapters.gguf_weight_shapes(str(args.gguf))
        found = gguf_adapters.discover_writeback_targets(shapes, width)
        artifact_layers = sorted(found["targets"])
        missing = sorted(set(range(layer_count)) - set(artifact_layers))
        report["gguf"] = {
            "artifact": str(args.gguf), "writeback_layers": len(artifact_layers),
            "missing_layers": missing[:24],
            "unmapped_width_tensors": found["unmapped_writeback_width"][:8],
            "agree": not missing and len(artifact_layers) >= layer_count,
        }
        if missing:
            report["notes"].append(
                f"the artifact has no residual-write projection for {len(missing)} captured "
                f"layers; a merge with --gguf-targets auto would refuse, which is the honest "
                f"outcome (wrong checkpoint or a different hidden width).")
        else:
            report["next"] = [
                f"python -m jdewitt.spanfit build --gguf-in {args.gguf} --in-place "
                f"--records {out} --shape perlayer --scale 1.0 --gguf-targets auto",
                f"python -m jdewitt.spanfit axes --records {out} --out axes.pt --shape shared",
            ]
    else:
        report["notes"].append(
            "no --gguf: pass the artifact the capture must agree with to get the exact merge "
            "command and a layer-count cross-check.")
        report["next"] = [
            f"python -m jdewitt.spanfit build --gguf-in <artifact.gguf> --in-place "
            f"--records {out} --shape perlayer --scale 1.0 --gguf-targets auto",
        ]
    atomic_json(out.with_suffix(out.suffix + ".capture.json"), report)
    del model
    source_context.__exit__(None, None, None)
    return report
