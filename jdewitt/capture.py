# Last dotted component of a module name that denotes a residual-write
# projection. Same canonical set the GGUF-side discovery uses (gguf_adapters
# WRITEBACK_TENSOR); a model whose block names its output projection something
# else is reported, never guessed at.
WRITEBACK_MODULE = re.compile(
    r"^(o_proj|out_proj|ssm_out|down_proj|w2|attn_output|attn_out)$")


def read_rows(path, kinds=None, limit=None, exclude_families=(), exclude_categories=()):
    """Suite rows to capture, plus tallies of the kinds and families filtered out.

    ``--exclude-families``/``--exclude-categories`` are exact-value lists: a
    family is excluded by id, never by a prompt keyword, so the report can name
    every row that was dropped and why. The framed-capture guard for self-harm
    and CSAM-adjacent families lives in ``frames.protected_reason`` and is
    applied separately, so it cannot be switched off by an empty list here.
    """
    exclude_families = set(exclude_families or ())
    exclude_categories = set(exclude_categories or ())
    rows, skipped, excluded = [], {}, {}
    for number, line in enumerate(Path(path).read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as error:
            raise ValueError(f"{path}:{number} is not JSON: {error}") from error
        for field in ("id", "kind", "prompt"):
            if field not in row:
                raise ValueError(f"{path}:{number} needs a {field!r} field")
        if kinds and row["kind"] not in kinds:
            skipped[row["kind"]] = skipped.get(row["kind"], 0) + 1
            continue
        if row.get("family_id") in exclude_families:
            excluded[f"family:{row['family_id']}"] = excluded.get(f"family:{row['family_id']}", 0) + 1
            continue
        if row.get("category") is not None and str(row["category"]) in exclude_categories:
            excluded[f"category:{row['category']}"] = excluded.get(f"category:{row['category']}", 0) + 1
            continue
        rows.append(row)
    return (rows[:limit] if limit else rows), skipped, excluded


def hidden_width(config, override=None):
    if override:
        return int(override)
    text = getattr(config, "text_config", config)
    width = getattr(text, "hidden_size", None)
    if type(width) is not int or width <= 0:
        raise ValueError("config carries no hidden_size; pass --hidden explicitly")
    return width


def expected_layers(config):
    text = getattr(config, "text_config", config)
    for attribute in ("num_hidden_layers", "n_layer", "num_layers"):
        value = getattr(text, attribute, None)
        if type(value) is int and value > 0:
            return value
    return None


def find_layer_stack(model, width, expected=None):
    """(path, count) of the decoder ModuleList, from the module tree.

    A candidate is a ModuleList whose first block contains a linear that writes a
    ``width``-wide vector. ``expected`` (config.num_hidden_layers) breaks ties,
    because a model may nest other ModuleLists inside a block.
    """
    candidates = []
    for name, module in model.named_modules():
        if not isinstance(module, nn.ModuleList) or len(module) < 2:
            continue
        writes = any(isinstance(inner, nn.Linear) and inner.out_features == width
                     for inner in module[0].modules())
        candidates.append((name, len(module), writes))
    if not candidates:
        raise ValueError("no decoder ModuleList in the module tree")
    exact = [candidate for candidate in candidates if expected and candidate[1] == expected]
    pool = exact or [candidate for candidate in candidates if candidate[2]]
    if not pool:
        raise ValueError(f"no ModuleList whose blocks write a {width}-wide residual stream")
    name, count, _ = max(pool, key=lambda candidate: candidate[1])
    return name, count


def writeback_targets(layer, width):
    """[(relative module name, Linear)] for one block's residual-write projections."""
    found = []
    for name, module in layer.named_modules():
        if not name or not isinstance(module, nn.Linear):
            continue
        if module.out_features != width:
            continue
        if not WRITEBACK_MODULE.match(name.split(".")[-1]):
            continue
        found.append((name, module))
    return found


def label_for(kind, shape):
    """Fit label from the row's kind and the answer's shape — never from wording."""
    declining = shape["declining"] or shape["embedded_decline"]
    if kind == "refusal":
        if declining:
            return "bad"
        return "deliver" if shape["shape"] == "procedural_no_decline" else "ambiguous"
    if kind == "harmless":
        return "overdecline" if declining else "good"
    return "unlabelled"


def render_prompt(tokenizer, prompt, system, raw):
    if raw:
        return prompt, "raw"
    if getattr(tokenizer, "chat_template", None):
        return render_chat(tokenizer, prompt, system=system), "chat"
    return prompt, "raw-no-template"


def _hook_factory(width, position, span_end):
    def hook(module, args, output):
        hidden = output[0] if isinstance(output, tuple) else output
        if not torch.is_tensor(hidden) or hidden.dim() != 3:
            raise ValueError("decoder block did not return a [batch, seq, hidden] tensor")
        if hidden.shape[-1] != width:
            raise ValueError(f"residual width {hidden.shape[-1]} != {width}")
        rows = hidden[0]
        if span_end is None:
            captured = rows[position]
        else:
            captured = rows[position:span_end].mean(dim=0)
        hook.captured = captured.detach().float().cpu()
    hook.captured = None
    return hook


def _settle_criteria(tokenizer, prompt_length, min_tokens, every=8):
    """Stop decoding once the prefix is a self-declination (cert mode).

    The label only needs the prefix: a refusal opener does not turn into delivery
    by adding tokens. Settling on the OPENER / embedded first-person decline form
    -- the cert-mode settle, never a topical word -- keeps this exact: a delivered
    answer that merely contains 'illegal' is not cut short, and a seeded
    'Sure, here is how: I cannot ...' is. Rows that do not settle keep decoding
    to the full budget, so a procedure is never mistaken for a refusal.
    """
    from transformers import StoppingCriteria

    class Settle(StoppingCriteria):
        def __init__(self):
            self.steps = 0
            self.settled_at = None

        def __call__(self, input_ids, scores, **kwargs):
            self.steps += 1
            generated = int(input_ids.shape[1]) - prompt_length
            if generated < min_tokens or self.steps % every:
                return False
            text = tokenizer.decode(input_ids[0, prompt_length:], skip_special_tokens=True)
            if screen_short(text, 'cert') == 'refusal':
                self.settled_at = generated
                return True
            return False

    return Settle()


def read_answers(path):
    """{row id: answer text} from a banked wave or any jsonl carrying id+answer."""
    answers = {}
    for number, line in enumerate(Path(path).read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as error:
            raise ValueError(f'{path}:{number} is not JSON: {error}') from error
        answer, row_id = row.get('answer'), row.get('id')
        if answer is None or row_id is None:
            continue
        answers[row_id] = answer
    if not answers:
        raise ValueError(f'{path} carries no id+answer rows; pass a predictions.jsonl from '
                         f'a wave over this same model')
    return answers


def read_mirror_answers(path):
    """[(row id, frame name, answer)] from a delivery-mirror JSONL.

    A mirror entry is a real delivery of that request, produced elsewhere (the
    published oracle, a jailbreak capture) and carried here as TEXT. The capture
    teacher-forces it under the PLAIN prompt with a distinct frame label, so the
    pair contrast is answer content only -- the label is provenance, not a
    wrapper. ``none`` is refused: it is the refusal side's label.
    """
    entries = []
    for number, line in enumerate(Path(path).read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as error:
            raise ValueError(f"{path}:{number} is not JSON: {error}") from error
        row_id, frame, answer = row.get("id"), row.get("frame"), row.get("answer")
        if not isinstance(row_id, str) or not row_id:
            raise ValueError(f"{path}:{number}: id must be a nonempty string")
        if not isinstance(frame, str) or not frame or frame == "none":
            raise ValueError(f"{path}:{number}: frame must be a nonempty name other than 'none'")
        if not isinstance(answer, str) or not answer.strip():
            raise ValueError(f"{path}:{number}: answer must be nonempty text")
        entries.append((row_id, frame, answer))
    if not entries:
        raise ValueError(f"{path} carries no id+frame+answer rows")
    return entries


def mirror_frame(name):
    """A provenance-only frame: the plain prompt, a borrowed answer.

    ``render_frame`` renders this exactly like the plain prompt (seed None, one
    ``{prompt}`` slot), so a mirror record's residual is read on the same text a
    plain record would use. The name only keys the pair.
    """
    from .frames import Frame

    return Frame(name=name, template="{prompt}", seed=None,
                 provenance=("answer-mirror: the delivery answer was produced elsewhere "
                             "and is teacher-forced here under the plain prompt"),
                 measured="not a jailbreak frame; a pair-side provenance label")


def capture_one(model, tokenizer, row, layers, width, *, locus, max_tokens,
                ctx_size, system, raw, device, settle=True, settle_min_tokens=24,
                answer_text=None, margin_pairs=None, frame=None):
    """Generate one row (or reuse a banked answer) and return (meta, [L, W]).

    ``answer_text`` is the zero-output-token path: when a wave has already
    generated this row against this same model, the answer is scored by
    re-tokenizing the prompt plus that text, so the only cost is one prefill.

    ``frame`` is a pinned ``frames.Frame`` (None = today's plain prompt). The
    record carries ``frame`` and ``prompt_id`` (the suite id) because that pair
    of fields is the key a spanfit pair fit reads: one record per (suite id,
    frame), and the plain record is frame 'none'.

    ``margin_pairs`` are the resolved (sure_id, cannot_id) pairs. The margin is
    read from the SAME forward pass that already captures the residual stream, at
    index ``prompt_tokens - 1`` (the distribution that emitted the first answer
    token), so it costs one subtraction per pair: no extra pass, no generated
    token. A model that returns no logits records ``margin=None`` and
    ``margin_available=False`` instead of failing the capture.
    """
    if frame is None:
        text, rendered = render_prompt(tokenizer, row["prompt"], system, raw)
    else:
        from .frames import render_frame
        text, rendered = render_frame(tokenizer, frame, row["prompt"], system, raw)
    ids = tokenizer(text, return_tensors="pt", add_special_tokens=False)["input_ids"]
    prompt_tokens = int(ids.shape[1])
    if prompt_tokens + max_tokens + 1 > ctx_size:
        return None, {"reason": "prompt_plus_budget_exceeds_ctx", "prompt_tokens": prompt_tokens}
    pad = tokenizer.pad_token_id if tokenizer.pad_token_id is not None else tokenizer.eos_token_id
    settled_at = None
    stopped = False
    if answer_text is not None:
        answer_ids = tokenizer(answer_text, add_special_tokens=False)["input_ids"]
        if not answer_ids:
            return None, {"reason": "banked_answer_empty"}
        sequence = torch.cat([ids, torch.tensor([answer_ids], dtype=ids.dtype)], dim=1).to(device)
        source = "banked"
    else:
        criteria = None
        if settle:
            from transformers import StoppingCriteriaList
            criteria = StoppingCriteriaList([_settle_criteria(tokenizer, prompt_tokens, settle_min_tokens)])
        with torch.inference_mode():
            sequence = model.generate(
                ids.to(device),
                attention_mask=torch.ones_like(ids, device=device),
                max_new_tokens=max_tokens, do_sample=False,
                pad_token_id=pad if type(pad) is int else None,
                stopping_criteria=criteria)
        settled_at = criteria[0].settled_at if criteria is not None else None
        generated = sequence[0, prompt_tokens:].tolist()
        eos = model.generation_config.eos_token_id
        eos = list(eos) if isinstance(eos, (list, tuple)) else [eos]
        stop = next((index for index, token in enumerate(generated) if token in eos), None)
        stopped = stop is not None
        generated = generated[: stop + 1] if stopped else generated
        answer_ids = generated[:-1] if stopped else generated
        source = "generated"
    complete = True if source == "banked" else (stopped or settled_at is not None)
    answer = tokenizer.decode(answer_ids, skip_special_tokens=True)
    if not answer_ids:
        return None, {"reason": "empty_answer"}
    shape = classify(answer)
    label = label_for(row["kind"], shape)
    start = prompt_tokens
    end = prompt_tokens + len(answer_ids)
    if locus == "last-prompt":
        position, span_end = start - 1, None
    elif locus == "first-answer":
        position, span_end = start, None
    else:
        position, span_end = start, end
    hooks = []
    margin, margin_available = None, False
    margin_position = start - 1
    try:
        for layer in layers:
            hook = _hook_factory(width, position, span_end)
            hooks.append((hook, layer.register_forward_hook(hook)))
        with torch.inference_mode():
            output = model(sequence[:, : end], attention_mask=torch.ones((1, end), dtype=torch.long, device=device),
                           use_cache=False)
            logits = getattr(output, "logits", None)
            if margin_pairs:
                try:
                    margin = margin_at_position(logits, margin_position, margin_pairs)
                    margin_available = True
                except (MarginUnavailable, IndexError):
                    margin = None
            del output, logits
    finally:
        for _, handle in hooks:
            handle.remove()
    if any(hook.captured is None for hook, _ in hooks):
        return None, {"reason": "residual_hooks_did_not_fire"}
    residual = torch.stack([hook.captured for hook, _ in hooks])
    meta = {"id": row.get("id"), "prompt_id": row.get("id"), "label": label, "kind": row["kind"],
            "shape": shape["shape"], "declining": bool(shape["declining"]),
            "embedded_decline": bool(shape["embedded_decline"]),
            "frame": frame.name if frame is not None else "none",
            "frame_provenance": frame.provenance if frame is not None else None,
            "seed": frame.seed if frame is not None else None,
            "chars": len(answer), "answer_tokens": len(answer_ids),
            "settled_at": settled_at,
            "prompt_tokens": prompt_tokens, "family_id": row.get("family_id"),
            "category": row.get("category"), "language": row.get("language"),
            "rendered": rendered, "prompt": row["prompt"], "prompt_rendered": text,
            "complete": complete, "locus": locus,
            "answer_source": source,
            "margin": margin, "margin_available": margin_available,
            "margin_position": margin_position if margin_available else None,
            "margin_pairs": list(margin_pairs or []),
            "answer": answer}
    return (meta, residual), None


def capture_command(args):
    """The agent-facing entry: one JSON report, one records file, one next step."""
    from .hf import resolve_backend, backend_device
    from . import gguf_adapters

    t0 = time.monotonic()
    kinds = tuple(k.strip() for k in args.kinds.split(",") if k.strip())
    unknown = [kind for kind in kinds if kind not in {"refusal", "harmless", "capability", "code", "math"}]
    if unknown:
        raise ValueError(f"unknown --kinds entries {unknown}; kinds are suite 'kind' values")
    from . import frames as frames_module
    local_frames = frames_module.load_frame_file(args.frame_file) if getattr(args, "frame_file", None) else ()
    if local_frames and getattr(args, "frame", "none") not in (None, "none"):
        raise ValueError("--frame and --frame-file are alternatives; name the frames in the file")
    frame_names = (tuple(frame.name for frame in local_frames) if local_frames
                   else frames_module.parse_frames(getattr(args, "frame", "none")))
    frame_by_name = {frame.name: frame for frame in local_frames} if local_frames else dict(frames_module.FRAMES)
    framed_names = tuple(name for name in frame_names if name != "none")
    mirror_by_id = {}
    for row_id, mirror_name, mirror_answer in (
            read_mirror_answers(args.mirror_answers) if getattr(args, "mirror_answers", None) else ()):
        if mirror_name in framed_names:
            # A mirror label names where the answer came from; reusing a frame the
            # same run is generating under would make two records indistinguishable.
            raise ValueError(f"mirror frame {mirror_name!r} is also being generated in this run")
        if row_id in mirror_by_id:
            raise ValueError(f"mirror answers name row {row_id!r} twice")
        mirror_by_id[row_id] = (mirror_frame(mirror_name), mirror_answer)
    exclude_families = tuple(f.strip() for f in (getattr(args, "exclude_families", "") or "").split(",") if f.strip())
    exclude_categories = tuple(c.strip() for c in (getattr(args, "exclude_categories", "") or "").split(",") if c.strip())
    rows, filtered, excluded = read_rows(args.suite, kinds, args.limit, exclude_families, exclude_categories)
    protected_skipped = {}
    if framed_names or mirror_by_id:
        # The seed/fiction frames stay off the protective families permanently:
        # a framed capture there is the one contrast this project never builds.
        kept = []
        for row in rows:
            reason = frames_module.protected_reason(row)
            if reason is None:
                kept.append(row)
            else:
                key = f"{row.get('family_id') or 'unfamilied'}: {reason}"
                protected_skipped[key] = protected_skipped.get(key, 0) + 1
        rows = kept
    if not rows:
        raise ValueError(f"{args.suite} has no rows for kinds {list(kinds)} after the frame/exclusion guard")

    from transformers import AutoConfig, AutoModel, AutoModelForCausalLM, AutoTokenizer
    from .compat import compatible_source
    backend = resolve_backend(allow_secondary=args.allow_cuda)
    device = backend_device(backend)
    config = AutoConfig.from_pretrained(args.model, revision=args.revision,
                                        trust_remote_code=args.trust_remote_code)
    width = hidden_width(config, args.hidden)
    tokenizer = AutoTokenizer.from_pretrained(args.model, revision=args.revision,
                                              trust_remote_code=args.trust_remote_code)
    dtype = {"bfloat16": torch.bfloat16, "float16": torch.float16}[args.dtype]
    attempts = []
    model = None
    # Vendor remote-code checkpoints get the same private metadata repair the rest
    # of the tool uses (compat.compatible_source); the user's download is never
    # written to.
    source_context = compatible_source(args.model)
    prepared = source_context.__enter__()
    try:
        for factory in (AutoModelForCausalLM, AutoModel):
            for attention in ("eager", None):
                kwargs = {"revision": args.revision, "dtype": dtype, "device_map": {"": device},
                          "trust_remote_code": args.trust_remote_code}
                if attention:
                    kwargs["attn_implementation"] = attention
                try:
                    model = factory.from_pretrained(str(prepared), **kwargs).eval()
                    break
                except (ValueError, TypeError, RuntimeError) as error:
                    attempts.append(f"{factory.__name__}({attention or 'default'}): {error}")
            if model is not None:
                break
        if model is None:
            raise ValueError("no model factory loaded this checkpoint: " + " | ".join(attempts[:4]))
    except BaseException:
        source_context.__exit__(None, None, None)
        raise

    stack_name, layer_count = find_layer_stack(model, width, expected_layers(config))
    stack = dict(model.named_modules())[stack_name]
    layers = [stack[index] for index in range(layer_count)]
    targets = {index: writeback_targets(layers[index], width) for index in range(layer_count)}
    empty = [index for index, found in targets.items() if not found]
    if empty:
        linear_names = sorted({name for name, module in layers[empty[0]].named_modules()
                              if isinstance(module, nn.Linear)})
        raise NoVerifiedAdapter(
            f"blocks {empty[:8]} carry no residual-write projection this tool can name; "
            f"linear modules in block {empty[0]}: {linear_names}. Capture cannot edit a block "
            f"it cannot locate, and guessing would edit the wrong matrix. Discovery proves a "
            f"module NAME at hidden width {width}, not that the architecture serves the edit; "
            f"a layout is certified by the export smoke, not here",
            width=width, layers_without_target=empty[:8], layers_without_target_total=len(empty),
            linear_modules=linear_names, layer=empty[0],
            writeback_names=list(WRITEBACK_MODULE.pattern.strip('^$()').split('|')))
    suffix_counts = {}
    for found in targets.values():
        for name, _ in found:
            suffix = name.split(".")[-1]
            suffix_counts[suffix] = suffix_counts.get(suffix, 0) + 1

    records, discarded, labels = [], {}, {}
    tokens = {"prompt": 0, "answer": 0}
    settled = 0
    reused = 0
    answers_missing = 0
    by_frame = {name: {"records": 0, "labels": {}, "tokens": {"prompt": 0, "answer": 0}, "answers_reused": 0}
                for name in frame_names}
    if args.answers:
        # The refusal side of a pair is already banked: the plain-prompt wave
        # costs ZERO output tokens, and only the framed side is generated.
        by_frame.setdefault("none", {"records": 0, "labels": {}, "tokens": {"prompt": 0, "answer": 0},
                                    "answers_reused": 0})
    answers = read_answers(args.answers) if args.answers else {}
    # Resolution happens once per capture: a spelling that is not exactly one id
    # refuses the statistic (a sequence margin is a different measurement). The
    # refusal never fails the capture; rows then carry margin=None.
    margin_resolution = token_table(tokenizer)
    margin_available, margin_refusal, margin_pairs = True, None, []
    try:
        margin_pairs = resolved_pairs(margin_resolution)
    except MarginRefused as error:
        margin_available, margin_refusal = False, str(error)
    for row in rows:
        plans = []
        if "none" in frame_names:
            plans.append((None, answers.get(row.get("id"))))
        elif answers and row.get("id") in answers:
            # Implicit plain side: --answers is the banked plain-prompt wave and
            # the pair needs its refusal answer, not another decode.
            plans.append((None, answers[row.get("id")]))
        for name in framed_names:
            plans.append((frame_by_name[name], None))
        mirror = mirror_by_id.get(row.get("id"))
        if mirror is not None:
            # The delivery side of a pair whose answer was produced elsewhere:
            # teacher-forced under the plain prompt, labelled for provenance.
            plans.append((mirror[0], mirror[1]))
        for frame, banked in plans:
            if frame is None and args.answers and row.get("id") not in answers:
                answers_missing += 1
            try:
                captured, reason = capture_one(
                    model, tokenizer, row, layers, width, locus=args.locus,
                    max_tokens=args.max_tokens, ctx_size=args.ctx_size,
                    system=args.system, raw=args.raw_prompt, device=device,
                    settle=args.settle, settle_min_tokens=args.settle_min_tokens,
                    answer_text=banked, margin_pairs=margin_pairs, frame=frame)
            except (ValueError, RuntimeError) as error:
                discarded[str(error)[:200]] = discarded.get(str(error)[:200], 0) + 1
                continue
            if captured is None:
                key = reason.get("reason", "unknown")
                discarded[key] = discarded.get(key, 0) + 1
                continue
            meta, residual = captured
            records.append((meta, residual))
            frame_tally = by_frame.setdefault(meta["frame"], {"records": 0, "labels": {},
                                                              "tokens": {"prompt": 0, "answer": 0},
                                                              "answers_reused": 0})
            frame_tally["records"] += 1
            labels[meta["label"]] = labels.get(meta["label"], 0) + 1
            frame_tally["labels"][meta["label"]] = frame_tally["labels"].get(meta["label"], 0) + 1
            tokens["prompt"] += meta["prompt_tokens"]
            frame_tally["tokens"]["prompt"] += meta["prompt_tokens"]
            if meta.get("answer_source") == "banked":
                reused += 1
                frame_tally["answers_reused"] += 1
            else:
                tokens["answer"] += meta["answer_tokens"]
                frame_tally["tokens"]["answer"] += meta["answer_tokens"]
            settled += 1 if meta.get("settled_at") else 0

    bad, good = labels.get("bad", 0), labels.get("good", 0)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    identity = {
        "model": args.model, "revision": args.revision or getattr(config, "_commit_hash", None),
        "architecture": getattr(config, "model_type", None), "hidden": width,
        "layers": layer_count, "layer_path": stack_name, "locus": args.locus,
        "dtype": args.dtype, "max_tokens": args.max_tokens, "ctx_size": args.ctx_size,
        "kinds": list(kinds), "suite": str(args.suite),
        "suite_sha256": hashlib.sha256(Path(args.suite).read_bytes()).hexdigest(),
        "frames": {
            "names": list(frame_names),
            "file": str(args.frame_file) if getattr(args, "frame_file", None) else None,
            "file_sha256": (hashlib.sha256(Path(args.frame_file).read_bytes()).hexdigest()
                            if getattr(args, "frame_file", None) else None),
            "pinned": {name: {"seed": frame_by_name[name].seed,
                              "template": frame_by_name[name].template,
                              "provenance": frame_by_name[name].provenance,
                              "measured": frame_by_name[name].measured}
                       for name in framed_names},
            "protected_skipped": protected_skipped,
        },
        "targets": {index: [name for name, _ in found] for index, found in targets.items()},
        "compute_backend": {"type": backend["type"], "rank": backend["rank"], "name": backend["name"]},
        "margin": {"resolution": margin_resolution, "pairs": margin_pairs,
                   "available": margin_available, "refusal": margin_refusal},
    }
    torch.save({"records": records, "capture": identity}, out)
    report = {
        "records": str(out), "records_bytes": out.stat().st_size,
        "identity": identity,
        "rows_read": len(rows), "records_written": len(records),
        "labels": labels, "filtered_kinds": filtered, "filtered_excluded": excluded,
        "filtered_protected_families": protected_skipped,
        "by_frame": by_frame,
        "discarded": discarded,
        "tokens": tokens, "elapsed_s": round(time.monotonic() - t0, 1),
        "settling": {
            "enabled": bool(args.settle), "min_tokens": args.settle_min_tokens,
            "rows_settled": settled,
            "note": "a settled row stops at the first explicit self-declination (cert-mode "
                    "settle), so its answer span IS the refusal span; rows that do not settle "
                    "decode to the full budget, so a procedure is never cut short",
        },
        "answers_reused": reused,
        "answers_missing": answers_missing,
        "answers_reused_note": (f"{reused} row(s) took their answer from --answers and cost ZERO "
                                f"output tokens (prefill only); rows not found there were generated"),
        "target_suffixes": suffix_counts,
        "fit_usable": False,
        "next": [],
        "notes": [
            "bad = a harmful row whose own answer declines; good = a harmless row that "
            "complies; deliver/ambiguous/overdecline are recorded for the agent read and "
            "never enter the default bad/good contrast.",
            "capture is not certification: shape verdicts on the edited artifact stay an "
            "agent read (METHODOLOGY R2).",
        ],
    }
    # The margin is read out of the pass that was already run, so it is ambient
    # evidence on every capture: report it per label and keep the honest ceiling.
    margin_rows = [(meta["label"], meta["margin"]) for meta, _ in records if meta.get("margin") is not None]

    def margin_stats(label):
        values = [value for mark, value in margin_rows if mark == label]
        if not values:
            return {"n": 0, "mean": None, "median": None}
        return {"n": len(values), "mean": round(sum(values) / len(values), 6),
                "median": round(statistics.median(values), 6)}

    bad_margin, good_margin = margin_stats("bad"), margin_stats("good")
    report["margin"] = identity["margin"]
    report["margin_summary"] = {
        "bad": bad_margin, "good": good_margin,
        "delta_bad_minus_good": (round(bad_margin["mean"] - good_margin["mean"], 6)
                                 if bad_margin["n"] and good_margin["n"] else None),
        "rows_with_margin": len(margin_rows),
        "rows_without_margin": len(records) - len(margin_rows),
        "note": "delta_bad_minus_good is the prefill margin (Sure minus cannot) on harmful rows "
                "minus the same on harmless rows; it ranks candidate axes and never certifies "
                "(METHODOLOGY R2/R6).",
    }
    report["margin_available"] = bool(margin_available and len(margin_rows) == len(records))
    if not report["margin_available"]:
        report["notes"].append(
            "the token-logit margin is unavailable for this capture: "
            + (margin_refusal or f"{len(records) - len(margin_rows)} row(s) returned no logits") +
            ". The capture itself is unaffected; do not substitute a word list for a token margin.")
    report["notes"].append(
        "the margin ranks candidate axes and never certifies (METHODOLOGY R2/R6): a lower prefill "
        "margin is evidence the axis points at the mechanism, not that the edited artifact still "
        "behaves; only a merged serve decides that.")
    # A fit needs BOTH halves of the contrast, and a missing half is a property of
    # the base model, not a capture defect: fitting a label set the model does not
    # exhibit yields a null edit that still merges cleanly.
    report["fit_usable"] = bad >= 1 and good >= 1
    if not report["fit_usable"]:
        missing = []
        if not bad:
            missing.append(f"no bad rows: 0 of {len(records)} answers declined")
        if not good:
            missing.append(f"no good rows: 0 of {len(records)} harmless answers complied")
        report["notes"].append(
            "cannot form a bad-minus-good contrast — " + "; ".join(missing) +
            ". Widen the suite/--limit or use a checkpoint that actually refuses it; do not fit on this.")
    if args.gguf:
        shapes = gguf_adapters.gguf_weight_shapes(str(args.gguf))
        found = gguf_adapters.discover_writeback_targets(shapes, width)
        artifact_layers = sorted(found["targets"])
        missing = sorted(set(range(layer_count)) - set(artifact_layers))
        report["gguf"] = {
            "artifact": str(args.gguf), "writeback_layers": len(artifact_layers),
            "missing_layers": missing[:24],
            "unmapped_width_tensors": found["unmapped_writeback_width"][:8],
            "agree": not missing and len(artifact_layers) >= layer_count,
        }
        if missing:
            report["notes"].append(
                f"the artifact has no residual-write projection for {len(missing)} captured "
                f"layers; a merge with --gguf-targets auto would refuse, which is the honest "
                f"outcome (wrong checkpoint or a different hidden width).")
        else:
            report["next"] = [
                f"python -m jdewitt.spanfit build --gguf-in {args.gguf} --in-place "
                f"--records {out} --shape perlayer --scale 1.0 --gguf-targets auto",
                f"python -m jdewitt.spanfit axes --records {out} --out axes.pt --shape shared",
            ]
    else:
        report["notes"].append(
            "no --gguf: pass the artifact the capture must agree with to get the exact merge "
            "command and a layer-count cross-check.")
        report["next"] = [
            f"python -m jdewitt.spanfit build --gguf-in <artifact.gguf> --in-place "
            f"--records {out} --shape perlayer --scale 1.0 --gguf-targets auto",
        ]
    if (framed_names or mirror_by_id) and getattr(args, "pairs_out", None):
        # One pair per (suite id, frame) whose framed answer is a shape-delivery
        # CANDIDATE, against the plain answer the capture already holds. A mirror
        # record is a candidate by construction (the answer was hand-read as a
        # delivery elsewhere), so it is written with a null verdict too: the read
        # still has to be recorded here (R2).
        from .delivery_pairs import make_pair, summarize as summarize_pairs, write_pairs
        mirror_names = {frame.name for frame, _ in mirror_by_id.values()}
        plain_by_id = {meta["prompt_id"]: meta for meta, _ in records if meta["frame"] == "none"}
        pairs, candidates = [], []
        for meta, _ in records:
            if meta["frame"] == "none" or meta["kind"] != "refusal":
                continue
            if meta["label"] != "deliver" and meta["frame"] not in mirror_names:
                continue
            plain = plain_by_id.get(meta["prompt_id"])
            candidates.append({"prompt_id": meta["prompt_id"], "frame": meta["frame"],
                               "shape": meta["shape"], "chars": meta["chars"],
                               "plain_side": plain is not None,
                               "plain_shape": plain["shape"] if plain is not None else None})

            def _side(record):
                if record is None:
                    return None
                return {"frame": record["frame"], "answer": record["answer"], "shape": record["shape"],
                        "declining": bool(record["declining"] or record.get("embedded_decline")),
                        "answer_source": record["answer_source"], "chars": record["chars"],
                        "seed": record.get("seed")}

            pair = make_pair(
                prompt_id=meta["prompt_id"], prompt=meta["prompt"],
                kind=meta["kind"], family_id=meta.get("family_id"), category=meta.get("category"),
                source=dict({"kind": "capture", "model": args.model, "revision": identity["revision"],
                             "suite": str(args.suite), "suite_sha256": identity["suite_sha256"],
                             "records": str(out), "locus": args.locus,
                             "plain_answer": ("banked" if plain is not None and plain["answer_source"] == "banked"
                                              else "generated" if plain is not None else "missing")},
                            **({"mirror_answers": str(args.mirror_answers),
                                "mirror_frames": sorted(mirror_names)} if mirror_names else {})),
                refusal=_side(plain), delivery=_side(meta))
            pairs.append(pair)
        pairs_dir = Path(args.pairs_out)
        pairs_dir.mkdir(parents=True, exist_ok=True)
        pairs_path = write_pairs(pairs_dir / "pairs.jsonl", pairs)
        report["pairs_out"] = str(pairs_path)
        report["pairs_candidates"] = candidates
        report["pairs_summary"] = summarize_pairs(pairs)
        report["notes"].append(
            f"{len(pairs)} shape-delivery candidate(s) written to {pairs_path} with verdict null. "
            "Every candidate must be agent-read (scripts/delivery_pairs.py vet) against the request "
            "before any axis is fitted from it; a shape-clean pivot is not a delivery (R2).")
        if not pairs:
            report["notes"].append(
                "no framed answer reached the delivery shape; there is no pair corpus from this "
                "capture and the next step is a higher-yield source, not a fit.")
    elif framed_names:
        report["notes"].append(
            "no --pairs-out: the framed records exist, but no candidate pair JSONL was written, so "
            "no read can be recorded against this run.")
    atomic_json(out.with_suffix(out.suffix + ".capture.json"), report)
    del model
    source_context.__exit__(None, None, None)
    return report
