"""Index every committed verification packet so prose numbers have an address.

Usage: python scripts/results_index.py > docs/RESULTS-INDEX.md

The whole moat of this tool is verification, so a number that lives only in prose
is a liability. This walks verification/ and prints one row per evidence file with
its size and sha256 prefix, plus whatever headline metrics the JSON exposes
(pass rates, counts, effect sizes). It is a table of record, not a gate: it does not
judge whether a claim is right, only that the claim has a file to point at, and a
doc that quotes a number without a row here is quoting something that was not
committed.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
VERIFIED = REPO / 'verification'
METRIC_KEYS = ('pass_rate', 'pass_rate_wilson', 'capability_passed', 'refusals_detected',
               'delivered_instead', 'invalid', 'rows', 'total', 'passed',
               'effect_size_cohens_h', 'delta', 'tensors_edited', 'elapsed_s',
               'paired_sign_flip_p_two_sided', 'p_two_sided')


def sha16(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 22), b''):
            digest.update(chunk)
    return digest.hexdigest()[:16]


def metrics(node, depth=0, out=None) -> dict:
    """Pull headline scalars out of a nested report without a schema guess."""
    out = {} if out is None else out
    if depth > 4:
        return out
    if isinstance(node, dict):
        for key, value in node.items():
            if key in METRIC_KEYS and isinstance(value, (int, float)) and not isinstance(value, bool):
                out.setdefault(key, value)
            else:
                metrics(value, depth + 1, out)
    elif isinstance(node, list):
        for item in node[:8]:
            metrics(item, depth + 1, out)
    return out


def main(argv=None) -> int:
    print('# Results index\n')
    print('Generated by `scripts/results_index.py`. Every number quoted in a doc '
          'should have a row here; a doc number with no row is a number that was '
          'never committed.\n')
    files = sorted(p for p in VERIFIED.rglob('*')
                   if p.is_file() and p.suffix in ('.json', '.jsonl'))
    print(f'{len(files)} evidence files under `verification/`\n')
    print('| file | bytes | sha256/16 | headline metrics |')
    print('|---|---:|---|---|')
    for path in files:
        relative = path.relative_to(REPO)
        size = path.stat().st_size
        line = ''
        if path.suffix == '.json':
            try:
                line = ', '.join(f'{key}={json.dumps(value)[:28]}'
                                 for key, value in list(metrics(
                                     json.loads(path.read_text())).items())[:8])
            except (json.JSONDecodeError, UnicodeDecodeError):
                line = 'unreadable json'
        else:
            lines = [l for l in path.read_text(errors='ignore').splitlines() if l.strip()]
            line = f'rows={len(lines)}'
        print(f'| `{relative}` | {size} | `{sha16(path)}` | {line or "—"} |')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
